// =======================================================
// ЧАСТИНА 1: ПІДГОТОВКА (ІНІЦІАЛІЗАЦІЯ)
// =======================================================

// Створюємо магічний об'єкт "socket", який автоматично знаходить 
// наш сервер і встановлює з ним постійне WebSocket з'єднання.
// Функція io() стала доступною завдяки тому, що ми підключили 
// бібліотеку socket.io в HTML-файлі.
const socket = io();

// "Хапаємо" наші HTML-елементи за їх ID, щоб ми могли 
// маніпулювати ними: додавати повідомлення, читати текст з поля вводу.
const messages = document.getElementById('messages'); // Це наш <ul> для повідомлень
const form = document.getElementById('form');         // Це наша <form>
const input = document.getElementById('input');       // Це наше поле <input>

// =======================================================
// ЧАСТИНА 2: ВІДОБРАЖЕННЯ ПОВІДОМЛЕНЬ (ЩО ПРИХОДИТЬ ВІД СЕРВЕРА)
// =======================================================

// Цей блок спрацює ОДИН РАЗ, коли ти тільки зайдеш у чат.
// Він слухає спеціальну подію 'all_messages', яку сервер надсилає
// новому користувачу, щоб показати йому всю історію чату.
socket.on('all_messages', function(msgArray) {
    // msgArray — це масив об'єктів (повідомлень), який прийшов із сервера.
    // Наприклад: [ {login: 'Artem', content: 'Привіт'}, {login: 'Boba', content: 'Як справи?'} ]

    // Для кожного повідомлення з історії ми виконуємо цей код:
    msgArray.forEach(msg => {
        // Створюємо в пам'яті новий HTML-тег <li>
        let item = document.createElement('li');
        // Записуємо в нього текст у форматі "логін : текст повідомлення"
        item.textContent = msg.login + ' : ' + msg.content;
        // Додаємо цей <li> в наш список <ul> на сторінці.
        messages.appendChild(item);
    });
    // Після того, як всі повідомлення додані, прокручуємо сторінку до самого низу.
    window.scrollTo(0, document.body.scrollHeight);
});

// Цей блок буде спрацьовувати КОЖЕН РАЗ, коли хтось (ти або інший юзер)
// відправляє НОВЕ повідомлення. Він слухає подію 'message'.
socket.on('message', function(msg) {
    // msg — це просто рядок тексту, який сервер розсилає всім. 
    // Наприклад: "Artem: Всім привіт!"

    // Створюємо новий <li>
    var item = document.createElement('li');
    // Вставляємо в нього текст повідомлення
    item.textContent = msg;
    // Додаємо його в кінець списку
    messages.appendChild(item);
    // Прокручуємо сторінку вниз, щоб побачити нове повідомлення.
    window.scrollTo(0, document.body.scrollHeight);
});


// =======================================================
// ЧАСТИНА 3: ВІДПРАВКА ПОВІДОМЛЕНЬ (ЩО ЙДЕ НА СЕРВЕР)
// =======================================================

// Навішуємо "слухач" на нашу форму. Він чекає на подію 'submit' 
// (це відбувається, коли ти натискаєш Enter або кнопку "Send").
form.addEventListener('submit', function (e) {
    // Забороняємо браузеру перезавантажувати сторінку.
    e.preventDefault();

    // Перевіряємо, чи не пусте поле вводу.
    if (input.value) {
        // Якщо там є текст, ми створюємо подію 'new_message' для сервера
        // і відправляємо разом з нею текст з поля вводу.
        socket.emit('new_message', input.value);
        
        // Очищуємо поле вводу, щоб можна було писати наступне повідомлення.
        input.value = '';
    }
});

// =======================================================
// ЧАСТИНА 4: ЗМІНА НІКНЕЙМУ (ДОДАТКОВИЙ ФУНКЦІОНАЛ)
// =======================================================

// Ця функція викликається один раз при завантаженні сторінки.
function changeNickname() {
    // Показує стандартне віконечко браузера з проханням ввести нік.
    let nickname = prompt('Choose your nickname');
    // Якщо користувач щось ввів і не натиснув "Скасувати",
    if (nickname) {
        // то ми відправляємо на сервер подію 'set_nickname' з цим текстом.
        socket.emit('set_nickname', nickname);
    }
}

// Викликаємо функцію, щоб запитати нікнейм одразу при вході.
changeNickname();