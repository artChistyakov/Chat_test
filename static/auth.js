// Знаходимо в HTML елемент з id="register-form" (це наша форма)
// і записуємо його в змінну, щоб далі з ним працювати.
const registerForm = document.getElementById('register-form');

// Додаємо до нашої форми "слухача подій". 
// Він буде чекати, поки користувач спробує відправити форму (подія 'submit').
// Коли це станеться, виконається функція, що написана нижче.
registerForm.addEventListener('submit', (event) => {
    
    // event — це об'єкт, який браузер автоматично створює при події.
    // event.preventDefault() — це найважливіша команда тут. Вона ЗАБОРОНЯЄ
    // браузеру перезавантажувати сторінку, що він робить за замовчуванням при відправці форми.
    event.preventDefault();

    // Це деструктуризація. Ми "витягуємо" з об'єкта registerForm (нашої форми)
    // поля вводу за їхніми атрибутами `name`.
    // Тепер у нас є змінні: login, password та passwordRepeat, які є нашими <input>-ами.
    const {login, password, passwordRepeat} = registerForm;

    // Робимо просту перевірку на клієнті: чи збігається текст у двох полях для пароля.
    // .value — це властивість, яка містить текст, введений користувачем.
    if(password.value !== passwordRepeat.value) {
        // Якщо паролі не збігаються, показуємо вікно з помилкою
        // і зупиняємо виконання функції за допомогою `return`.
        return alert("Passwords do not match");
    }

    // Готуємо дані для відправки на сервер.
    // Створюємо JavaScript-об'єкт з логіном та паролем.
    // JSON.stringify() перетворює цей об'єкт на текстовий рядок у форматі JSON.
    // Сервер очікує отримати саме текстовий рядок.
    const user = JSON.stringify({
        login: login.value,
        password: password.value
    });

    // Створюємо "листоношу" — об'єкт для відправки HTTP-запитів.
    const xhr = new XMLHttpRequest();

    // Налаштовуємо запит:
    // 'POST' — метод, який каже, що ми хочемо відправити дані на сервер.
    // '/api/register' — адреса на сервері, яка буде обробляти цей запит.
    xhr.open('POST', '/api/register');
    
    // ВАЖЛИВО: Встановлюємо заголовок. Це як написати на конверті "Всередині - JSON".
    // Без цього сервер може не зрозуміти, в якому форматі прийшли дані.
    xhr.setRequestHeader('Content-Type', 'application/json');

    // Відправляємо наш текстовий рядок `user` на сервер.
    xhr.send(user);

    // Це callback-функція. Вона спрацює, коли сервер завершить обробку 
    // і надішле нам відповідь.
    xhr.onload = () => {
        // Просто показуємо у вікні alert текст відповіді, який прислав сервер
        // (наприклад, "Registration is successful" або "User already exists").
        alert(xhr.response);
    }
});